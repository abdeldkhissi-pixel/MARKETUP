import { Domain } from '../types/marketup';
import {
  buildDomainFromBlueprint,
  CompactTopic,
  createLessonBlueprint,
  DomainBlueprint,
} from './curriculumBuilder';

export interface RawChapter {
  title: string;
  description: string;
  topics: CompactTopic[];
}

export interface RawDomain {
  id: string;
  order: number;
  title: string;
  shortTitle: string;
  description: string;
  objectives: [string, string, string, string];
  recommendedLevel: 'debutant' | 'intermediaire' | 'avance';
  accentColor: 'violet' | 'blue' | 'amber';
  chapters: RawChapter[];
}

export function compileRawDomain(raw: RawDomain): Domain {
  const bp: DomainBlueprint = {
    id: raw.id,
    order: raw.order,
    title: raw.title,
    shortTitle: raw.shortTitle,
    description: raw.description,
    objectives: raw.objectives,
    recommendedLevel: raw.recommendedLevel,
    accentColor: raw.accentColor,
    chapters: raw.chapters.map((ch, cIdx) => ({
      title: ch.title,
      description: ch.description,
      lessons: ch.topics.map((t, lIdx) =>
        createLessonBlueprint(t, cIdx * 5 + lIdx)
      ) as DomainBlueprint['chapters'][number]['lessons'],
    })) as DomainBlueprint['chapters'],
  };
  return buildDomainFromBlueprint(bp);
}

